pub(super) fn tool_definition(tool_id: &str) -> AppResult<AiToolDefinition> {
    let tool_id = required_text("工具 ID", tool_id)?;
    tool_definitions()
        .into_iter()
        .find(|tool| tool.id == tool_id)
        .ok_or_else(|| AppError::validation(format!("不支持的 AI 工具: {tool_id}")))
}
